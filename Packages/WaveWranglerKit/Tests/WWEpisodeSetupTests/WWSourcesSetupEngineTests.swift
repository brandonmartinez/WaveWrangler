        await consumer.value
        #expect(received.value >= 1)
        await engine!.shutdown()
        engine = nil
        for _ in 0..<200 where weakEngine != nil { await Task.yield() }
        #expect(weakEngine == nil, "engine leaked after observe + cancel + shutdown")
    }

