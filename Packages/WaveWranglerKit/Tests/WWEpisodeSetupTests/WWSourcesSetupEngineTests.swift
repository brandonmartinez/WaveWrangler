        #expect(WWSourcesStatusMapping.transfer(.notRequested(.availabilityOff)) == .downloadsOff)
        #expect(WWSourcesStatusMapping.transfer(.notRequested(.unsupportedLocation)) == .unsupportedLocation)
        #expect(WWSourcesStatusMapping.transfer(.notRequested(.awaitingAccess)) == .idle)
        #expect(WWSourcesStatusMapping.transfer(.requested) == .downloading(fraction: nil))
        #expect(WWSourcesStatusMapping.transfer(.inProgress(fractionCompleted: .unknown)) == .downloading(fraction: nil))
        #expect(WWSourcesStatusMapping.transfer(.inProgress(fractionCompleted: .known(0.5))) == .downloading(fraction: 0.5))
        let denied = AvailabilityObservation(observedAt: Date(), location: .unknown, access: .denied)
        #expect(WWSourcesStatusMapping.snapshot(denied).summary.text == "Access denied")
        #expect(WWSourcesStatusMapping.snapshot(nil) == .checking)
        #expect(WWSourcesStatusMapping.identity(.changed([.fileSize])) == .changed(differences: "size differ", acceptedByUser: false))
        #expect(WWSourcesStatusMapping.identity(.mismatch([.fileIdentifier])) == .mismatch(differences: "file id differ"))
        #expect(WWSourcesStatusMapping.residency(.downloading) == .cloudOnly)
        let missing = AvailabilityObservation(observedAt: Date(), location: .missing(lastKnownPathOccupied: .known(true)), access: .granted)
        #expect(WWSourcesStatusMapping.snapshot(missing).location == .missing(sameNamedFileAtOriginalLocation: true))
        // #90: an unusable grant or unobserved access on a missing file is not a permission problem.
        for access in [AccessState.needsRegrant, .staleBookmark, .unknown] {
            let gone = WWSourcesStatusMapping.snapshot(AvailabilityObservation(observedAt: Date(), location: .missing(lastKnownPathOccupied: .known(false)), access: access))
            #expect(gone.access == .notChecked(reason: "the file wasn't found"), "\(access)")
            #expect(gone.summary.text == "Not found", "\(access)")
        }
        // Denied stays denied, and a present file with an unusable grant still needs permission.
        #expect(WWSourcesStatusMapping.snapshot(AvailabilityObservation(observedAt: Date(), location: .unknown, access: .denied)).access == .denied)
        #expect(WWSourcesStatusMapping.snapshot(AvailabilityObservation(observedAt: Date(), location: .present, access: .needsRegrant)).access == .needsPermission)
    }
}

final class Counter: @unchecked Sendable {
    private let lock = NSLock()
    private var count = 0
    func increment() { lock.withLock { count += 1 } }
    var value: Int { lock.withLock { count } }
}

/// Wraps an in-memory store; an armed gate *suspends* (never blocks a thread) the next `record(for:)`
/// until released, so tests can hold a refresh in flight without starving the cooperative pool.
actor GatedDeviceAccessStore: DeviceAccessStore {
    private let base: InMemoryDeviceAccessStore
    private var armed = false
    private var waiting: CheckedContinuation<Void, Never>?
    private(set) var entered = false

    init(_ records: [DeviceAccessRecord] = []) {
        base = InMemoryDeviceAccessStore(records)
    }

    func arm() { armed = true; entered = false }

    func release() {
        armed = false
        waiting?.resume()
        waiting = nil
    }

    func record(for key: DeviceAccessKey) async throws -> DeviceAccessRecord? {
        if armed {
            armed = false
            entered = true
            await withCheckedContinuation { waiting = $0 }
        }
        return await base.record(for: key)
    }

    func records(in showID: ShowID) async throws -> [DeviceAccessRecord] { await base.records(in: showID) }
    func allRecords() async throws -> [DeviceAccessRecord] { await base.allRecords() }
    func save(_ record: DeviceAccessRecord) async throws { await base.save(record) }
    func save(_ records: [DeviceAccessRecord]) async throws { await base.save(records) }
    func removeRecord(for key: DeviceAccessKey) async throws { await base.removeRecord(for: key) }
    func removeRecords(in showID: ShowID) async throws { await base.removeRecords(in: showID) }
}
